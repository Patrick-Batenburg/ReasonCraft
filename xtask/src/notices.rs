//! `cargo run -p xtask -- notices`: the licence texts of the Rust crates
//! the app is built from, for its About page.
//!
//! Runs cargo-about 0.9.3 (installed as `docs/release.md` says)
//! over the app's run-time dependencies on every release platform (see
//! `xtask/about.toml`) and writes `app/reasoncraft/assets/licences/crates.txt`:
//! each distinct licence text once, with the crates under it. The file is
//! committed; regenerate it whenever `Cargo.lock` changes.

use std::collections::BTreeSet;
use std::process::Command;

use serde_json::Value;

use crate::{Result, workspace_dir, write};

/// The line that opens each licence in `crates.txt`; the app splits the
/// file on it (`shell::about::licences`, which repeats it).
pub const RULE: &str = "========================================================================";

pub fn notices() -> Result<()> {
    let root = workspace_dir();
    let out = Command::new("cargo")
        .current_dir(root)
        .args([
            "about", "generate", "--frozen", "--fail", "--format", "json",
        ])
        .args(["-m", "app/reasoncraft/Cargo.toml", "-c", "xtask/about.toml"])
        .output()?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        return Err(format!("cargo about failed (is it installed?):\n{err}").into());
    }
    let about: Value = serde_json::from_slice(&out.stdout)?;
    let mut entries = Vec::new();
    for licence in about["licenses"].as_array().ok_or("no `licenses` list")? {
        // The workspace's own crates are ReasonCraft, not third-party.
        let users: BTreeSet<String> = licence["used_by"]
            .as_array()
            .into_iter()
            .flatten()
            .map(|u| (&u["crate"]["name"], &u["crate"]["version"]))
            .filter(|(name, _)| name.as_str().is_some_and(|n| !n.starts_with("reasoncraft")))
            .map(|(name, version)| {
                format!(
                    "{} {}",
                    name.as_str().unwrap_or("?"),
                    version.as_str().unwrap_or("?")
                )
            })
            .collect();
        if users.is_empty() {
            continue;
        }
        let name = licence["name"].as_str().unwrap_or("?");
        let text = licence["text"].as_str().unwrap_or_default();
        let text: Vec<&str> = text.lines().map(str::trim_end).collect();
        entries.push((
            name.to_owned(),
            users.into_iter().collect::<Vec<_>>(),
            text.join("\n"),
        ));
    }
    entries.sort();
    entries.dedup();
    let mut file = String::from(
        "The Rust crates ReasonCraft is built from, and their licences.\n\
         Generated by `cargo run -p xtask -- notices` with cargo-about; do not edit.\n",
    );
    for (name, users, text) in &entries {
        file += &format!(
            "\n{RULE}\n{name}\nUsed by: {}\n\n{}\n",
            users.join(", "),
            text.trim_matches('\n')
        );
    }
    let path = root.join("app/reasoncraft/assets/licences/crates.txt");
    std::fs::create_dir_all(path.parent().ok_or("no parent folder")?)?;
    write(&path, file.as_bytes())?;
    println!("{} licence texts for the crates", entries.len());
    Ok(())
}
